// Writes supabase/seed.sql from the made-up sample leads, so the database starts with demo data.
// Run: node supabase/make-seed.mjs
import { writeFileSync } from 'node:fs'
import { sampleLeads, NOT_FOUND } from '../src/data/sampleLeads.js'

const val = (v) => (v === NOT_FOUND || v === undefined || v === null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`)
const arr = (a) => `array[${a.map(val).join(', ')}]::text[]`
const json = (o) => `'${JSON.stringify(o).replaceAll("'", "''")}'::jsonb`

const rows = sampleLeads.map((l) =>
  `  (${[val(l.id), val(l.property), val(l.city), val(l.state), val(l.assetType), val(l.units), val(l.engine), val(l.distressType), val(l.stage), val(l.eventDate), val(l.buyer), val(l.buyerTrackRecord), val(l.receiver), arr(l.signals), val(l.priorLoanPerUnit), val(l.salePricePerUnit), val(l.exitPath), json(l.sources), 'true'].join(', ')})`,
)

const sql = `-- Made-up sample leads (is_sample = true). Generated by make-seed.mjs; safe to run more than once.
insert into public.leads (id, property, city, state, asset_type, units, engine, distress_type, stage, event_date, buyer, buyer_track_record, receiver, signals, prior_loan_per_unit, sale_price_per_unit, exit_path, sources, is_sample)
values
${rows.join(',\n')}
on conflict (id) do nothing;
`
writeFileSync(new URL('./seed.sql', import.meta.url), sql)
console.log(`Wrote ${rows.length} sample leads to supabase/seed.sql`)
